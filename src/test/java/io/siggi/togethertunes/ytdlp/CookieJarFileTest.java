package io.siggi.togethertunes.ytdlp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** The shared cookies file through private copies ({@link CookieJarFile}). */
class CookieJarFileTest {
    static final String HEADER = "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp.  Do not edit.\n";

    @TempDir
    Path dir;

    private final List<String> warnings = new CopyOnWriteArrayList<>();

    @AfterEach
    void reset() {
        CookieJarFile.resetWarnings();
    }

    static String line(String domain, String name, String value) {
        return domain + "\tTRUE\t/\tTRUE\t1900000000\t" + name + "\t" + value;
    }

    private Path shared(String... cookies) throws Exception {
        Path file = dir.resolve("cookies.txt");
        Files.writeString(file, HEADER + "\n" + String.join("\n", cookies) + (cookies.length > 0 ? "\n" : ""));
        return file;
    }

    private CookieJarFile.Call open(Path file) {
        return CookieJarFile.open(file.toString(), dir, warnings::add);
    }

    /** Rewrites a call's private file as yt-dlp does when it ends: its whole jar. */
    private static void ytdlpWrites(CookieJarFile.Call call, String... cookies) throws Exception {
        Files.writeString(call.file(), HEADER + "\n" + String.join("\n", cookies) + (cookies.length > 0 ? "\n" : ""));
    }

    private static List<String> cookieLines(Path file) throws Exception {
        List<String> out = new ArrayList<>();
        for (String l : Files.readAllLines(file)) {
            if (!l.isBlank() && (!l.startsWith("#") || l.startsWith("#HttpOnly_"))) {
                out.add(l);
            }
        }
        return out;
    }

    // ------------------------------------------------------------------ format

    @Test
    void parseAndWriteRoundTrip() throws Exception {
        String text = "# Netscape HTTP Cookie File\r\n"
                + "# a comment\n"
                + "\n"
                + ".youtube.com\tTRUE\t/\tTRUE\t1900000000\tPREF\tf6=40000000&tz=Europe.Berlin\n"
                + "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1900000000\tLOGIN_INFO\tAFm:QUQ\n"
                + "   \n"
                + "www.youtube.com\tFALSE\t/watch\tFALSE\t0\tSESSION\twith\ttab\n"
                + ".google.com\tTRUE\t/\tFALSE\t0\tEMPTY\t\n";
        CookieJarFile.Jar jar = CookieJarFile.parse(text);
        assertEquals(List.of("# Netscape HTTP Cookie File", "# a comment"), jar.comments());
        assertEquals(4, jar.cookies().size());
        CookieJarFile.Cookie login = jar.cookies().get(new CookieJarFile.Key(".youtube.com", "/", "LOGIN_INFO"));
        assertTrue(login.httpOnly());
        CookieJarFile.Cookie session = jar.cookies().get(new CookieJarFile.Key("www.youtube.com", "/watch", "SESSION"));
        assertEquals("0", session.expiry(), "an expiry of 0 is a session cookie, kept as written");
        assertEquals("FALSE", session.includeSubdomains());
        assertEquals("with\ttab", session.value());
        assertEquals("", jar.cookies().get(new CookieJarFile.Key(".google.com", "/", "EMPTY")).value());

        String written = CookieJarFile.write(jar);
        assertEquals("# Netscape HTTP Cookie File\n# a comment\n\n"
                + ".youtube.com\tTRUE\t/\tTRUE\t1900000000\tPREF\tf6=40000000&tz=Europe.Berlin\n"
                + "#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1900000000\tLOGIN_INFO\tAFm:QUQ\n"
                + "www.youtube.com\tFALSE\t/watch\tFALSE\t0\tSESSION\twith\ttab\n"
                + ".google.com\tTRUE\t/\tFALSE\t0\tEMPTY\t\n", written);
        assertEquals(jar, CookieJarFile.parse(written));
        // no comments: the standard header is written
        assertEquals("# Netscape HTTP Cookie File\n", CookieJarFile.write(CookieJarFile.parse("")));
    }

    @Test
    void malformedFilesAreRejected() {
        assertThrows(CookieJarFile.MalformedException.class, () -> CookieJarFile.parse("hello world\n"));
        assertThrows(CookieJarFile.MalformedException.class,
                () -> CookieJarFile.parse(".youtube.com\tTRUE\t/\tTRUE\t0\tNAME\n"));
        assertThrows(CookieJarFile.MalformedException.class, () -> CookieJarFile.parse("{\"cookies\":[]}"));
    }

    // ------------------------------------------------------------------ merge

    @Test
    void twoCallsChangingDifferentCookiesBothKept() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"), line(".youtube.com", "B", "1"), line(".youtube.com", "C", "1"));
        CookieJarFile.Call first = open(file);
        CookieJarFile.Call second = open(file);
        assertNotEquals(first.file(), second.file());
        assertEquals(Files.readString(file), Files.readString(first.file()), "the private file is a copy");
        // each rewrites its whole jar, as yt-dlp does
        ytdlpWrites(first, line(".youtube.com", "A", "2"), line(".youtube.com", "B", "1"), line(".youtube.com", "C", "1"));
        ytdlpWrites(second, line(".youtube.com", "A", "1"), line(".youtube.com", "B", "1"), line(".youtube.com", "C", "1"),
                line(".youtube.com", "D", "new"));
        first.close();
        second.close();
        assertEquals(List.of(line(".youtube.com", "A", "2"), line(".youtube.com", "B", "1"), line(".youtube.com", "C", "1"),
                line(".youtube.com", "D", "new")), cookieLines(file));
        assertFalse(Files.exists(first.file()));
        assertFalse(Files.exists(second.file()));
        assertEquals(List.of(), warnings);
        // the header and comments once, at the top
        assertTrue(Files.readString(file).startsWith(HEADER + "\n" + line(".youtube.com", "A", "2")),
                Files.readString(file));
    }

    @Test
    void theSameCookieChangedTwiceTheLaterMergeWins() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"));
        CookieJarFile.Call first = open(file);
        CookieJarFile.Call second = open(file);
        ytdlpWrites(second, line(".youtube.com", "A", "from-second"));
        ytdlpWrites(first, line(".youtube.com", "A", "from-first"));
        second.close();
        first.close();
        assertEquals(List.of(line(".youtube.com", "A", "from-first")), cookieLines(file));
    }

    @Test
    void removalsAndFlagChanges() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"), line(".youtube.com", "EXPIRED", "x"),
                line(".youtube.com", "B", "1"));
        CookieJarFile.Call call = open(file);
        CookieJarFile.Call other = open(file);
        // yt-dlp dropped an expired cookie and marked B HttpOnly
        ytdlpWrites(call, line(".youtube.com", "A", "1"), "#HttpOnly_" + line(".youtube.com", "B", "1"));
        ytdlpWrites(other, line(".youtube.com", "A", "1"), line(".youtube.com", "EXPIRED", "x"),
                line(".youtube.com", "B", "1"), line(".youtube.com", "C", "other"));
        call.close();
        other.close();
        assertEquals(List.of(line(".youtube.com", "A", "1"), "#HttpOnly_" + line(".youtube.com", "B", "1"),
                line(".youtube.com", "C", "other")), cookieLines(file),
                "the other call kept EXPIRED unchanged, so the removal stands");
    }

    @Test
    void anUnchangedCallDoesNotRewrite() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"));
        FileTime old = FileTime.fromMillis(1_000_000_000_000L);
        Files.setLastModifiedTime(file, old);
        Object key = Files.readAttributes(file, java.nio.file.attribute.BasicFileAttributes.class).fileKey();
        try (CookieJarFile.Call call = open(file)) {
            // yt-dlp rewrote the jar with its own header but the same cookies
            Files.writeString(call.file(), "# Netscape HTTP Cookie File\n# other header\n\n" + line(".youtube.com", "A", "1") + "\n");
        }
        try (CookieJarFile.Call call = open(file)) {
            assertNotNull(call.file());
        }
        assertEquals(old, Files.getLastModifiedTime(file));
        assertEquals(key, Files.readAttributes(file, java.nio.file.attribute.BasicFileAttributes.class).fileKey());
        assertEquals(List.of(), warnings);
    }

    @Test
    void aMalformedPrivateFileIsNotMerged() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"));
        String before = Files.readString(file);
        CookieJarFile.Call call = open(file);
        Files.writeString(call.file(), "not a cookies file\n");
        call.close();
        assertEquals(before, Files.readString(file));
        assertFalse(Files.exists(call.file()));
        assertEquals(1, warnings.size(), warnings.toString());

        // cut off in the middle of a line (yt-dlp killed while writing)
        CookieJarFile.Call cut = open(file);
        Files.writeString(cut.file(), HEADER + "\n" + line(".youtube.com", "A", "1") + "\n.youtube.com\tTRUE\t/\tTRUE\t1900000000\tB\tpart");
        cut.close();
        assertEquals(before, Files.readString(file));
        // values never appear in warnings
        for (String w : warnings) {
            assertFalse(w.contains("part") || w.contains("1900000000"), w);
        }
    }

    @Test
    void permissionsAreKeptAndSymlinksAreWrittenThrough() throws Exception {
        Path real = shared(line(".youtube.com", "A", "1"));
        Files.setPosixFilePermissions(real, PosixFilePermissions.fromString("rw-r-----"));
        Path link = Files.createSymbolicLink(dir.resolve("link.txt"), real);
        try (CookieJarFile.Call call = open(link)) {
            assertEquals("rw-------", PosixFilePermissions.toString(Files.getPosixFilePermissions(call.file())));
            ytdlpWrites(call, line(".youtube.com", "A", "2"));
        }
        assertTrue(Files.isSymbolicLink(link), "the link isn't replaced");
        assertEquals(List.of(line(".youtube.com", "A", "2")), cookieLines(real));
        assertEquals("rw-r-----", PosixFilePermissions.toString(Files.getPosixFilePermissions(real)));
        try (var files = Files.list(dir)) {
            assertEquals(List.of(), files.filter(p -> p.getFileName().toString().endsWith(".tmp")).toList(),
                    "no temp files left");
        }
    }

    @Test
    void aNotWritableFileStillGetsPrivateCopiesAndWarnsOnce() throws Exception {
        Path file = shared(line(".youtube.com", "A", "1"));
        String before = Files.readString(file);
        Files.setPosixFilePermissions(file, PosixFilePermissions.fromString("r--------"));
        try {
            for (int i = 0; i < 3; i++) {
                try (CookieJarFile.Call call = open(file)) {
                    assertNotNull(call.file());
                    assertEquals(List.of("--cookies", call.file().toString()), call.args());
                    ytdlpWrites(call, line(".youtube.com", "A", "changed" + i));
                }
            }
            assertEquals(before, Files.readString(file));
            assertEquals(1, warnings.size(), warnings.toString());
            assertTrue(warnings.get(0).contains("isn't writable"), warnings.get(0));
        } finally {
            Files.setPosixFilePermissions(file, PosixFilePermissions.fromString("rw-------"));
        }
    }

    @Test
    void aMissingFileIsIgnored() {
        try (CookieJarFile.Call call = open(dir.resolve("gone.txt"))) {
            assertNull(call.file());
            assertEquals(List.of(), call.args());
        }
        assertEquals(1, warnings.size());
        try (CookieJarFile.Call call = CookieJarFile.open(null, dir, warnings::add)) {
            assertNull(call.file());
        }
        assertEquals(1, warnings.size());
    }

    @Test
    void readersNeverSeeAPartialFile() throws Exception {
        List<String> many = new ArrayList<>();
        for (int i = 0; i < 2000; i++) {
            many.add(line(".youtube.com", "C" + i, "v".repeat(40)));
        }
        Path file = shared(many.toArray(new String[0]));
        AtomicBoolean stop = new AtomicBoolean();
        AtomicReference<String> bad = new AtomicReference<>();
        CountDownLatch started = new CountDownLatch(4);
        List<Thread> readers = new ArrayList<>();
        for (int r = 0; r < 4; r++) {
            readers.add(Thread.ofVirtual().start(() -> {
                started.countDown();
                while (!stop.get()) {
                    try {
                        String text = Files.readString(file);
                        CookieJarFile.Jar jar = CookieJarFile.parse(text);
                        if (jar.cookies().size() < 2000 || !text.endsWith("\n")) {
                            bad.set("partial file: " + jar.cookies().size() + " cookies");
                        }
                    } catch (Exception e) {
                        bad.set(e.toString());
                    }
                }
            }));
        }
        started.await();
        for (int i = 0; i < 40; i++) {
            try (CookieJarFile.Call call = open(file)) {
                List<String> changed = new ArrayList<>(many);
                changed.add(line(".youtube.com", "ROUND", Integer.toString(i)));
                ytdlpWrites(call, changed.toArray(new String[0]));
            }
        }
        stop.set(true);
        for (Thread t : readers) {
            t.join();
        }
        assertNull(bad.get());
        assertTrue(cookieLines(file).contains(line(".youtube.com", "ROUND", "39")));
    }

    @Test
    void concurrentCallsKeepEveryChange() throws Exception {
        Path file = shared(line(".youtube.com", "BASE", "1"));
        List<Thread> threads = new ArrayList<>();
        AtomicReference<Throwable> failed = new AtomicReference<>();
        for (int i = 0; i < 16; i++) {
            int n = i;
            threads.add(Thread.ofVirtual().start(() -> {
                try (CookieJarFile.Call call = open(file)) {
                    List<String> lines = new ArrayList<>(cookieLines(call.file()));
                    lines.add(line(".youtube.com", "T" + n, "x"));
                    ytdlpWrites(call, lines.toArray(new String[0]));
                } catch (Throwable t) {
                    failed.set(t);
                }
            }));
        }
        for (Thread t : threads) {
            t.join();
        }
        assertNull(failed.get());
        List<String> lines = cookieLines(file);
        assertEquals(17, lines.size(), lines.toString());
    }
}
