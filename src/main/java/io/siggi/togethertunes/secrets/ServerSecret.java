package io.siggi.togethertunes.secrets;

import io.siggi.togethertunes.config.ConfigLoader;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileAlreadyExistsException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.nio.file.attribute.FileAttribute;
import java.nio.file.attribute.PosixFileAttributeView;
import java.nio.file.attribute.PosixFilePermission;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Base64;
import java.util.EnumSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Loads the server's 256-bit secret key.
 *
 * <p>Sources, in order:
 * <ol>
 *   <li>the environment variable {@value #ENV_VAR} (base64, standard or URL-safe alphabet,
 *       padding optional, 32 bytes). When it is set, {@code secret.key} is neither read nor
 *       created.</li>
 *   <li>{@code <data>/secret.key}: one line of base64 (32 bytes). If it doesn't exist, a new
 *       random key is generated and written with permissions 0600 (the data directory is created
 *       if needed). The file is written to a temporary file first and then linked into place, so
 *       a crash never leaves a half-written key and two processes can't both create one.</li>
 * </ol>
 *
 * <p>A key that is present but malformed is an error: the server must not silently replace a
 * key that existing ciphertexts depend on. An existing file readable by group or others only
 * produces a warning.
 */
public final class ServerSecret {
    /** Environment variable holding the key as base64. */
    public static final String ENV_VAR = ConfigLoader.SECRET_KEY_ENV;
    /** File name of the key inside the data directory. */
    public static final String FILE_NAME = "secret.key";
    /** Key length in bytes (AES-256). */
    public static final int KEY_BYTES = 32;

    private static final Set<PosixFilePermission> OWNER_ONLY =
            EnumSet.of(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE);

    /** Where a loaded key came from. */
    public enum Source {
        /** The {@value #ENV_VAR} environment variable. */
        ENVIRONMENT,
        /** An existing {@code secret.key} file. */
        FILE,
        /** A {@code secret.key} file generated by this load. */
        GENERATED
    }

    /**
     * A loaded key.
     *
     * @param cipher   the AES-GCM helper built from the key
     * @param source   where the key came from
     * @param file     the key file, or {@code null} for {@link Source#ENVIRONMENT}
     * @param warnings non-fatal problems to log (e.g. a too permissive key file)
     */
    public record Loaded(SecretCipher cipher, Source source, Path file, List<String> warnings) {
        public Loaded {
            warnings = List.copyOf(warnings);
        }
    }

    private ServerSecret() {
    }

    /**
     * Loads the key from the environment or {@code <dataDir>/secret.key}, generating the file if
     * neither exists.
     *
     * @throws SecretKeyException if the key is malformed or the file can't be read or written
     */
    public static Loaded load(Path dataDir, Map<String, String> env) throws SecretKeyException {
        List<String> warnings = new ArrayList<>();
        String fromEnv = env.get(ENV_VAR);
        if (fromEnv != null && !fromEnv.isBlank()) {
            byte[] key = decode(fromEnv, "Environment variable " + ENV_VAR);
            try {
                return new Loaded(new SecretCipher(key), Source.ENVIRONMENT, null, warnings);
            } finally {
                Arrays.fill(key, (byte) 0);
            }
        }
        Path file = dataDir.resolve(FILE_NAME);
        Source source = Source.FILE;
        if (!Files.exists(file, LinkOption.NOFOLLOW_LINKS)) {
            if (generate(file)) {
                source = Source.GENERATED;
            }
        }
        byte[] key = readFile(file, warnings);
        try {
            return new Loaded(new SecretCipher(key), source, file, warnings);
        } finally {
            Arrays.fill(key, (byte) 0);
        }
    }

    /** Generates a new random key as base64 text (for tests and for setting {@value #ENV_VAR}). */
    public static String generateBase64() {
        byte[] key = new byte[KEY_BYTES];
        new SecureRandom().nextBytes(key);
        try {
            return Base64.getEncoder().encodeToString(key);
        } finally {
            Arrays.fill(key, (byte) 0);
        }
    }

    /**
     * Creates {@code file} with a new key, unless another process created it first.
     *
     * @return whether this call created the file
     */
    private static boolean generate(Path file) throws SecretKeyException {
        Path dir = file.toAbsolutePath().getParent();
        Path tmp = null;
        try {
            Files.createDirectories(dir);
            boolean posix = supportsPosix(dir);
            FileAttribute<?>[] attrs = posix
                    ? new FileAttribute<?>[] {PosixFilePermissions.asFileAttribute(OWNER_ONLY)}
                    : new FileAttribute<?>[0];
            tmp = Files.createTempFile(dir, ".secret.key.", ".tmp", attrs);
            if (posix) {
                // createTempFile honours the attribute, but be explicit in case of an odd umask.
                Files.setPosixFilePermissions(tmp, OWNER_ONLY);
            }
            byte[] text = (generateBase64() + "\n").getBytes(StandardCharsets.US_ASCII);
            try (OutputStream out = Files.newOutputStream(tmp, StandardOpenOption.WRITE,
                    StandardOpenOption.TRUNCATE_EXISTING, StandardOpenOption.SYNC)) {
                out.write(text);
            } finally {
                Arrays.fill(text, (byte) 0);
            }
            try {
                Files.createLink(file, tmp);
                return true;
            } catch (FileAlreadyExistsException e) {
                return false; // someone else won the race; use their key
            } catch (UnsupportedOperationException | IOException e) {
                if (Files.exists(file, LinkOption.NOFOLLOW_LINKS)) {
                    return false;
                }
                // No hard links on this file system: fall back to a rename.
                Files.move(tmp, file, StandardCopyOption.ATOMIC_MOVE);
                tmp = null;
                return true;
            }
        } catch (IOException e) {
            throw new SecretKeyException("Could not create " + file + ": " + e, e);
        } finally {
            if (tmp != null) {
                try {
                    Files.deleteIfExists(tmp);
                } catch (IOException ignored) {
                    // a leftover temp file holds no key anyone uses
                }
            }
        }
    }

    private static byte[] readFile(Path file, List<String> warnings) throws SecretKeyException {
        if (!Files.isRegularFile(file)) {
            throw new SecretKeyException(file + " is not a regular file");
        }
        if (supportsPosix(file)) {
            try {
                Set<PosixFilePermission> perms = Files.getPosixFilePermissions(file);
                Set<PosixFilePermission> extra = EnumSet.copyOf(perms);
                extra.removeAll(EnumSet.of(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE,
                        PosixFilePermission.OWNER_EXECUTE));
                if (!extra.isEmpty()) {
                    warnings.add(file + " has permissions " + PosixFilePermissions.toString(perms)
                            + "; it should be readable only by its owner (chmod 600)");
                }
            } catch (IOException e) {
                warnings.add("Could not check the permissions of " + file + ": " + e);
            }
        }
        byte[] bytes;
        try {
            bytes = Files.readAllBytes(file);
        } catch (IOException e) {
            throw new SecretKeyException("Could not read " + file + ": " + e, e);
        }
        String text = new String(bytes, StandardCharsets.US_ASCII);
        Arrays.fill(bytes, (byte) 0);
        return decode(text, file.toString());
    }

    private static byte[] decode(String text, String where) throws SecretKeyException {
        String s = text.strip();
        byte[] key;
        try {
            if (s.indexOf('-') >= 0 || s.indexOf('_') >= 0) {
                key = Base64.getUrlDecoder().decode(s);
            } else {
                key = Base64.getDecoder().decode(s);
            }
        } catch (IllegalArgumentException e) {
            throw new SecretKeyException(where + " is not valid base64");
        }
        if (key.length != KEY_BYTES) {
            int len = key.length;
            Arrays.fill(key, (byte) 0);
            throw new SecretKeyException(where + " must hold " + KEY_BYTES + " bytes (base64), not " + len);
        }
        return key;
    }

    private static boolean supportsPosix(Path path) {
        Path p = path.toAbsolutePath();
        while (p != null && !Files.exists(p)) {
            p = p.getParent();
        }
        return p != null && Files.getFileAttributeView(p, PosixFileAttributeView.class) != null;
    }
}
